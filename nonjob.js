/* 求人ではない行を見分ける（2026-11-14・松岡さん指示「同じような行がまた入ってこないよう、取り込みの段階で弾く」）
   求人DB に、カジュアル面談の受付フォーム・会社説明会・セミナー・座談会・イベント・日付の過ぎた選考会が
   「求人」として入ってくることがある（媒体の取り込み元が、求人と同じ枠で募集している）。
   fetch-jobs.js がこれで判定して載せず、ログに名指しする。Airtable の行は消さない（直すなら「募集状況」を募集停止に）。

   ⚠ 本物の求人を落とさないこと。次は求人なので当てない：
     「イベントマーケター」「イベントディレクター」「セミナー講師」「セミナー企画運営」「説明会対応の採用担当」
     「カジュアル面談可能！【首都圏限定】マンション管理…」（求人の見出しに面談のしやすさを書いているだけ）
     日付の無い「1day選考会」「即日内定 選考会」（選考会という形の実際の求人）
   見るのは 職種・募集ポジション と 求人タイトル だけ（本文は見ない）。 */

const NONJOB = [
  // カジュアル面談の受付（「カジュアル面談可能」「カジュアル面談OK」は求人の売り文句なので除く）
  [/カジュアル面談(?!(可能|可|OK|ok|歓迎|も可|からでも|も実施|あり))/, 'カジュアル面談の受付'],
  // 説明会・セミナー・座談会・イベント（「〜講師」「〜企画」「〜対応」のような職種は除く）
  [/(会社説明会|オンライン説明会|合同説明会|説明会集客|説明選考会|採用セミナー|キャリア＆ライフセミナー|ミドル・シニアセミナー|休日セミナー|社長座談会|座談会(?!.*(運営|企画|担当))|MeetUP|ミートアップ|Meetup|オンラインイベント】|UIJターンイベント)/i, 'セミナー・説明会・イベント'],
];

/* 「11/8(日) 1day選考会」「【10月23日(金)開催】」のように日付の付いた選考会・説明会で、日付が過ぎたもの */
const DATED = /(\d{1,2})\s*[\/月]\s*(\d{1,2})\s*日?\s*[（(]?[月火水木金土日]?[）)]?[^】]{0,12}?(開催|選考会|説明会|イベント|選考用)|(選考会|説明会|開催)[^\d]{0,12}(\d{1,2})\s*[\/月]\s*(\d{1,2})/;

function pastDate(m, d, today) {
  const [ty, tm] = today.split('-').map(Number);
  let y = ty;
  if (m - tm > 6) y = ty - 1;        // 1月に「12/10開催」を見たら去年
  else if (tm - m > 6) y = ty + 1;   // 12月に「1/15開催」を見たら来年
  const iso = `${y}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`;
  return iso < today ? iso : null;
}

function nonJobReason(text, today) {
  const s = String(text || '');
  for (const [re, why] of NONJOB) {
    if (!re.test(s)) continue;
    // 「オープンポジション（※カジュアル面談希望の方もこちら）」は応募も受ける求人なので載せる
    if (why === 'カジュアル面談の受付' && /オープンポジション/.test(s)) continue;
    return why;
  }
  if (!DATED.test(s)) return null;
  /* 日付が複数あるとき（「11/8・15 1day選考用」）は最後の開催日で判断する。1つでも先の日付があれば載せる */
  const days = [];
  for (const m of s.matchAll(/(\d{1,2})\s*[\/月]\s*(\d{1,2})日?((?:\s*[・、,]\s*\d{1,2}日?)*)/g)) {
    const mo = Number(m[1]);
    if (mo < 1 || mo > 12) continue;
    [m[2], ...(m[3].match(/\d{1,2}/g) || [])].forEach(d => { if (d >= 1 && d <= 31) days.push([mo, Number(d)]); });
  }
  if (!days.length) return null;
  const past = days.map(([mo, d]) => pastDate(mo, d, today));
  if (past.some(p => !p)) return null;   // 今日以降の開催日がある
  return `開催日（${past.sort().pop()}）が過ぎた選考会・説明会`;
}

module.exports = { nonJobReason };
